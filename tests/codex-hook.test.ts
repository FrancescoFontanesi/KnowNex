import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import {
  cp,
  copyFile,
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rm,
  writeFile,
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import test from 'node:test';
import type { TestContext } from 'node:test';

async function temporary(t: TestContext) {
  const root = await mkdtemp(join(tmpdir(), 'knownex hook regression '));
  t.after(async () => {
    assert.equal(dirname(root), resolve(tmpdir()));
    await rm(root, { recursive: true, force: true });
  });
  return root;
}

test('this repository registers only the feed for Stop, with no capture or SessionEnd hook', async () => {
  const config = JSON.parse(await readFile('.codex/hooks.json', 'utf8'));
  assert.deepEqual(Object.keys(config.hooks).sort(), [
    'Stop',
    'UserPromptSubmit',
  ]);
  assert.doesNotMatch(JSON.stringify(config), /stop\.cjs/);
});

test(
  'il comando Stop configurato funziona sia in PowerShell sia in cmd.exe',
  { skip: process.platform !== 'win32' },
  async (t) => {
    const config = JSON.parse(await readFile('.codex/hooks.json', 'utf8'));
    const declared: string = config.hooks.Stop[0].hooks[0].command;
    const scriptArgument = declared.match(/"[^"\r\n]+\.cjs"$/)?.[0];
    assert.ok(
      scriptArgument,
      'hook command must end with a quoted script path',
    );
    for (const shell of ['powershell', 'cmd']) {
      await t.test(shell, async (subtest) => {
        const root = await temporary(subtest);
        await mkdir(join(root, '.codex/hooks'), { recursive: true });
        const script = join(root, '.codex/hooks/feed.cjs');
        await copyFile('.codex/hooks/feed.cjs', script);
        await cp('src', join(root, 'src'), { recursive: true });
        await copyFile('package.json', join(root, 'package.json'));
        const command =
          declared.slice(0, -scriptArgument.length) + '"' + script + '"';
        const input = JSON.stringify({
          hook_event_name: 'Stop',
          session_id: 'synthetic-regression',
          turn_id: 'turn-' + shell,
          last_assistant_message: 'Synthetic final',
        });
        const env = { ...process.env };
        delete env.KNOWNEX_CAPTURE;
        delete env.KNOWNEX_WORKSPACE;
        const result =
          shell === 'powershell'
            ? spawnSync(
                'powershell.exe',
                ['-NoProfile', '-NonInteractive', '-Command', command],
                { input, encoding: 'utf8', windowsHide: true, env },
              )
            : spawnSync(
                process.env.ComSpec || 'cmd.exe',
                ['/C', '"' + command + '"'],
                {
                  input,
                  encoding: 'utf8',
                  windowsHide: true,
                  windowsVerbatimArguments: true,
                  env,
                },
              );
        assert.ifError(result.error);
        assert.equal(result.status, 0, result.stderr);
        assert.equal(result.stderr, '');
        assert.deepEqual(JSON.parse(result.stdout), {});
        const [frame] = (
          await readFile(
            join(root, '.knownex/internal/feed/project.jsonl'),
            'utf8',
          )
        )
          .trimEnd()
          .split('\n')
          .map((line) => JSON.parse(line));
        assert.equal(frame.block.event.text, 'Synthetic final');
      });
    }
  },
);

test('a Stop wrapper installed by an earlier release runs the inert stub without errors or writes', async (t) => {
  const root = await temporary(t);
  const hooks = join(root, 'node_modules/knownex/.codex/hooks');
  await mkdir(hooks, { recursive: true });
  await copyFile('.codex/hooks/stop.cjs', join(hooks, 'stop.cjs'));
  await mkdir(join(root, '.codex/hooks'), { recursive: true });
  // Exact wrapper generated by releases that still captured transcripts.
  const wrapper = join(root, '.codex/hooks/knownex-stop.cjs');
  await writeFile(
    wrapper,
    "const { resolve, join } = require('node:path');\n" +
      "const root = resolve(__dirname, '../..');\n" +
      'process.env.KNOWNEX_WORKSPACE = root;\n' +
      "process.env.KNOWNEX_PROJECT_FEED = '1';\n" +
      "process.env.KNOWNEX_PROVIDER = 'codex';\n" +
      "require(join(root, 'node_modules/knownex/.codex/hooks/stop.cjs'));\n",
  );
  const transcript = join(root, 'transcript.jsonl');
  await writeFile(transcript, '{"private":"PRIVATE_SYNTHETIC_CONTENT"}\n');
  const env = { ...process.env };
  delete env.KNOWNEX_CAPTURE;
  for (const event of ['Stop', 'SessionEnd']) {
    const result = spawnSync(process.execPath, [wrapper], {
      cwd: root,
      encoding: 'utf8',
      windowsHide: true,
      timeout: 10000,
      env,
      input: JSON.stringify({
        hook_event_name: event,
        session_id: 'synthetic-regression',
        transcript_path: transcript,
        last_assistant_message: 'PRIVATE_SYNTHETIC_CONTENT',
      }),
    });
    assert.ifError(result.error);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stderr, '');
    assert.deepEqual(JSON.parse(result.stdout), {});
  }
  assert.deepEqual((await readdir(root)).sort(), [
    '.codex',
    'node_modules',
    'transcript.jsonl',
  ]);
  assert.deepEqual(await readdir(join(root, '.codex/hooks')), [
    'knownex-stop.cjs',
  ]);
});
